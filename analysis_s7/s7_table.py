"""Writes paper_artifacts/tab/s7_validity.tex
from data_v2/s7/cd_replay.json. Shares in percent with the 95% Wilson interval, one decimal as computed there.
usage: python3 analysis/s7_table.py"""
import os as _os, sys as _sys  # release layout: modules live in these folders of the repository
_R = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
_sys.path[:0] = [_os.path.join(_R, _d) for _d in ("tripwire_v2", "tripwire", "experiments_v2", "analysis_v2", "analysis_s7", "scripts", "testbed")]
import json, os

T = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cd = json.load(open(os.path.join(T, "data_v2/s7/cd_replay.json")))


def cell(k, n, lo, hi):
    return f"{100 * k / n:.1f} ({lo:.1f}--{hi:.1f}) & {k:,}/{n:,}"


rows = []
for st, name in (("dev", "Development"), ("heldout", "Held-out")):
    c2, d = cd[st]["c2"]["v2b_deleg"], cd[st]["d"]
    ml = d["mis_legit_refused"]
    rows.append(f"{name} & {cell(c2['runs_amb'], c2['runs'], *c2['wilson'])} & "
                f"{cell(d['collide'], d['values'], *d['collide_wilson'])} & {cell(ml['k'], ml['n'], *ml['wilson'])} \\\\")
out = ["% generated by analysis/s7_table.py from data_v2/s7/cd_replay.json",
       "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
       " & \\multicolumn{2}{c}{Clean runs refused $\\downarrow$} & \\multicolumn{2}{c}{Values in two or more sets $\\downarrow$} & \\multicolumn{2}{c}{Legitimate values refused $\\downarrow$} \\\\",
       "Suites & \\% (95\\% CI) & count & \\% (95\\% CI) & count & \\% (95\\% CI) & count \\\\",
       "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
open(os.path.join(T, "paper_artifacts/tab/s7_validity.tex"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
