      f"messages such as a file-added or clone notice; {len(e['errors_fn'])} heuristic-free fields read as typed, long "
      "typed values such as street addresses, opening hours and serialized file lists. Question 2 agreement is moderate "
      f"(kappa {e['all']['kappa_q2']}), so the third-party share is a rough figure. {len(e['disagreements_q1'])} question-1 disagreements are "
