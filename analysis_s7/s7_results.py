for st in ("heldout", "dev"):
    for arm, x in cd[st]["c2"].items():
        L.append(f"| {st} | {arm} | {x['runs']} | {x['runs_amb']} ({x['pct']}%, 95% Wilson interval {x['wilson'][0]}% to {x['wilson'][1]}%) | {x['calls_amb']} | {x['amb_gt']} of {x['calls_amb']} |")
