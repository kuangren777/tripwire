# check d
L += ["## Check d. Source-set collisions and first-hit label by value origin", "",
      "Unit: a control-argument value of a side-effecting call in the none-configuration runs, replayed with the "
      "v2b_deleg index. Origin: attacker = in the injected strings and not in the default environment or request; "
      "legitimate = in the default environment or request and in no injected string.", "",
      "| Suites | Values | In two or more source sets | Attacker-origin values with an admitted label | Legitimate-origin values with a refused label |",
      "|---|---|---|---|---|"]
