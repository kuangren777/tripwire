pr, a, b, c1, cd, e = J("parse_rate.json"), J("a_bridge.json"), J("b_repeat_score.json"), J("c1_natural_docs.json"), J("cd_replay.json"), J("e_score.json")


def pct(x):
    """'k of n, p%, 95% Wilson interval lo% to hi%'"""
    p = x.get("pct", round(100 * x["k"] / x["n"], 1) if x["n"] else None)
    return f"{x['k']} of {x['n']}, {p}% (95% Wilson interval {x['wilson'][0]}% to {x['wilson'][1]}%)"


L = ["# S7 results: offline validity checks for TripWire v2", "",
     "Pre-registration: analysis/AMENDMENT_s7.md (54bcb19f7) and its addendum 1 (fca95613c). Generated by "
     "analysis/s7_results.py from data_v2/s7/. Every share is a percentage of the stated unit with a 95% Wilson interval "
     "unless a row says otherwise. Counts carry no interval. Metrics marked post hoc were added after the first output "
     "of their check and are not in the AMENDMENT.", "",
     f"API spend: check b ${b['spend_usd']}, check e ${e['spend_usd']}, total ${round(b['spend_usd'] + e['spend_usd'], 2)} of the $10 cap. 0 GPU-h. No new attack text.", ""]

