def corrected(d, suite, fname):
    """ROPE's effect-based ASR correction (ext/rope/runs/corrections.py), applied to every configuration alike."""
    return bool(corrected_security(d, suite, int(re.sub(r"\D", "", fname[:-5]) or -1)))
sys.path.insert(1, f"{T}/scripts")
from h1_synthesis_split import SUITES, synthesis_tasks  # noqa: E402

D = f"{T}/data_v2/v2_heldout"
ALL = ["gpt-4o-mini-2024-07-18", "gpt-4o-2024-08-06", "qwen3-235b-a22b-instruct-2507"]
ARMS = ["rope", "tripwire_strict_v2", "tripwire_strict_v21"]


def load(model, arm):
    out = {}
    for f in glob.glob(f"{D}/{model}/{arm}/*/*/user_task_*/*/*.json"):
        p = f.split("/")
        d = json.load(open(f))
        if "utility" not in d:
            return None
        clean = p[-2] == "none"
        out[(model, p[-4], p[-3], p[-2], p[-1])] = (clean, bool(d["utility"]) if clean else corrected(d, p[-4], p[-1]))
    return out if len(out) == 620 else None


def rates(cells, keys):
    a = [cells[k][1] for k in keys if not cells[k][0]]
    c = [cells[k][1] for k in keys if cells[k][0]]
    return 100 * sum(a) / len(a), 100 * sum(c) / len(c), sum(c), len(c)


def exact(cells, keys):
    a = [cells[k][1] for k in keys if not cells[k][0]]
    c = [cells[k][1] for k in keys if cells[k][0]]
    return Fraction(100 * sum(a), len(a)), Fraction(100 * sum(c), len(c))


def signed(v, nd):
    return ("+" if v >= 0 else "$-$") + fmt(abs(v), nd)


def neg(v, nd):
    return ("$-$" if v < 0 else "") + fmt(abs(v), nd)


def write_tex(out, cells, keys, models, s0, slo, shi, u0, ulo, uhi):
    """tab/v21.tex (Table v21) and tab/v21_numbers.tex (the macros the v2.1 paragraph prints), both from the exact
    values of this run, each rounded once with fmtnum to one decimal, the table's precision."""
    short = {"gpt-4o-mini-2024-07-18": "gpt-4o-mini", "gpt-4o-2024-08-06": "gpt-4o"}
    rows = []
    for m in models + ["pooled"]:
        ks = [k for k in keys if m == "pooled" or k[0] == m]
        rows.append(short.get(m, m) + " & " + " & ".join(f"{fmt(x, 1)} / {fmt(y, 1)}" for x, y in (exact(cells[a], ks) for a in ARMS)) + " \\\\")
    rows.append(f"v2.1 minus ROPE & & & {signed(s0, 1)} / {signed(-u0, 1)} \\\\")
    rows.append(f"95\\% CI & & & [{neg(slo, 1)}, {neg(shi, 1)}] / [{neg(-uhi, 1)}, {neg(-ulo, 1)}] \\\\")
    tab = ("\\begin{tabular}{@{}lccc@{}}\n\\toprule\n"
           "Model & ROPE (cached) & \\textbf{strict v2 (ours)} & \\textbf{strict v2.1 (ours)} \\\\\n\\midrule\n"
           + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    P = {a: exact(cells[a], keys) for a in ARMS}
    e = out["exact"]
    mac = {"VTwoOneCUvTwo": fmt(P["tripwire_strict_v2"][1], 1), "VTwoOneCU": fmt(P["tripwire_strict_v21"][1], 1),
           "VTwoOneCUGain": fmt(P["tripwire_strict_v21"][1] - P["tripwire_strict_v2"][1], 1),
           "VTwoOneASRvTwo": fmt(P["tripwire_strict_v2"][0], 1), "VTwoOneASR": fmt(P["tripwire_strict_v21"][0], 1),
           "VTwoOneASRRise": fmt(P["tripwire_strict_v21"][0] - P["tripwire_strict_v2"][0], 1),
           "VTwoOneGap": fmt(s0, 1), "VTwoOneCILo": fmt(slo, 1), "VTwoOneCIHi": fmt(shi, 1),
           "VTwoOneAttacked": str(e["n_attacked"]), "VTwoOneOnly": str(e["v21_only"]), "VTwoOnly": str(e["v2_only"]),
           "VTwoSucc": str(e["successes"]["tripwire_strict_v2"]), "VTwoOneSucc": str(e["successes"]["tripwire_strict_v21"]),
           "VTwoOneTopThree": str(e["v21_only_in_top3"])}
    assert slo >= 0 or "VTwoOneCILo" in mac
    nums = "% AUTO-GENERATED by scripts/h1_v21_compare.py -- do not edit by hand.\n" + "".join(
        f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in mac.items())
    for name, text in (("v21.tex", tab), ("v21_numbers.tex", nums)):
        open(f"{T}/paper_artifacts/tab/{name}", "w").write(text)
    out["macros"] = mac


def main():
    models = [m for m in ALL if load(m, "tripwire_strict_v21") is not None]
    if not models:
        sys.exit("no model has 620 finished v2.1 cells")
    cells = {a: {} for a in ARMS}
    for m in models:
        for a in ARMS:
            d = load(m, a)
            assert d is not None, (m, a)
            cells[a].update(d)
    keys = sorted(cells["rope"])
    assert all(set(cells[a]) == set(keys) for a in ARMS)
    out = {"models": models, "per_model": {}, "pooled": {}}
    print("models:", ", ".join(models))
    for m in models + ["pooled"]:
        ks = [k for k in keys if m == "pooled" or k[0] == m]
        row = {a: dict(zip(("ASR", "CU", "CU_n", "N_clean"), rates(cells[a], ks))) for a in ARMS}
        (out["pooled"] if m == "pooled" else out["per_model"]).update({m: row} if m != "pooled" else row)
        print(f"{m[:24]:24} " + "  ".join(f"{a.replace('tripwire_', '')}: ASR {row[a]['ASR']:5.2f} CU {row[a]['CU']:5.1f}"
                                         for a in ARMS))
    SYN = set()
    for sn in SUITES:
        SYN |= {(sn, i) for i in synthesis_tasks(sn)[0]}
    split = {}
    for part in ("syn", "other"):
        ks = [k for k in keys if cells["rope"][k][0] and (((k[1], k[2]) in SYN) == (part == "syn"))]
        split[part] = {a: f"{sum(cells[a][k][1] for k in ks)}/{len(ks)}" for a in ARMS}
        print(f"clean {part:5}: " + "  ".join(f"{a}: {v}" for a, v in split[part].items()))
    out["split"] = split
    by_task = collections.defaultdict(list)
    for k in keys:
        by_task[(k[1], k[2])].append(k)
    tasks = sorted(by_task)
    rng = random.Random(0)

    def gaps(ts):
        s = [0, 0, 0]; c = [0, 0, 0]
        for t in ts:
            for k in by_task[t]:
                cl, r = cells["rope"][k]; x = cells["tripwire_strict_v21"][k][1]
                if cl:
                    c[0] += r; c[1] += x; c[2] += 1
                else:
                    s[0] += x; s[1] += r; s[2] += 1
        return Fraction(100 * (s[0] - s[1]), s[2]), Fraction(100 * (c[0] - c[1]), c[2])
    s0, u0 = gaps(tasks)
    ss, us = zip(*(gaps([tasks[rng.randrange(len(tasks))] for _ in tasks]) for _ in range(10_000)))
    ss, us = sorted(ss), sorted(us)
    out["v21_minus_rope_exact"] = {"security_pp": str(s0), "security_ci": [str(ss[250]), str(ss[9749])],
                                   "utility_gap_pp": str(-u0), "utility_ci": [str(-us[9749]), str(-us[250])]}
    out["v21_minus_rope"] = {"security_pp": round(float(s0), 2), "security_ci": [round(float(ss[250]), 2), round(float(ss[9749]), 2)],
                             "utility_gap_pp": round(float(-u0), 2), "utility_ci": [round(float(-us[9749]), 2), round(float(-us[250]), 2)]}
    print(f"v2.1 minus rope: security {float(s0):+.2f} pp [{float(ss[250]):+.2f}, {float(ss[9749]):+.2f}]  "
          f"utility gap {float(-u0):+.2f} pp [{float(-us[9749]):+.2f}, {float(-us[250]):+.2f}]")
    # exact counts behind the prose: attacked successes per configuration and the v2 -> v2.1 transitions
    att = [k for k in keys if not cells["rope"][k][0]]
    succ = {a: sum(cells[a][k][1] for k in att) for a in ARMS}
    up = [k for k in att if cells["tripwire_strict_v21"][k][1] and not cells["tripwire_strict_v2"][k][1]]
    dn = [k for k in att if cells["tripwire_strict_v2"][k][1] and not cells["tripwire_strict_v21"][k][1]]
    up_inj = collections.Counter((k[1], k[4][:-5]) for k in up)
    top3 = up_inj.most_common(3)
    clean = {a: sum(cells[a][k][1] for k in keys if cells[a][k][0]) for a in ARMS}
    n_clean = sum(1 for k in keys if cells["rope"][k][0])
    out["exact"] = {"n_attacked": len(att), "successes": succ, "n_clean": n_clean, "clean_completed": clean,
                    "v21_only": len(up), "v2_only": len(dn), "v21_only_top3_injections": top3,
                    "v21_only_in_top3": sum(n for _, n in top3),
                    "top3_all_github": all(sn == "github" for (sn, _), _ in top3)}
    print("exact:", out["exact"])
    write_tex(out, cells, keys, models, s0, ss[250], ss[9749], u0, us[250], us[9749])
    json.dump(out, open(f"{D}/v21_compare.json", "w"), indent=1)


if __name__ == "__main__":
    main()
