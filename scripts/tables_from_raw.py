def render(tex, gen_rows):
    """Write the generated cells into the paper's own layout: header, rules and bold markup come from the existing
    fragment, every body cell comes from gen_rows. Values are formatted once, in the t_* functions."""
    head, rest = tex.split("\\midrule", 1)
    body, foot = rest.split("\\bottomrule", 1)
    out, i = [], 0
    for line in body.split("\\\\"):
        if not line.strip() or line.replace("\\midrule", "").strip() == "":
            out.append(line); continue
        lead = line[:len(line) - len(line.lstrip())]
        pre = "\\midrule\n" if line.strip().startswith("\\midrule") else ""
        old = line.replace("\\midrule", "", 1).strip() if pre else line.strip()
        cells = []
        for o, g in zip(old.split("&"), gen_rows[i]):
            g = clean_cell(g).replace("%", "\\%")
            g = re.sub(r"(^|(?<=[\s\[]))-(?=\d)", "$-$", g)
            o_s = o.strip()
            if (not o_s and not g) or re.fullmatch(r"\\[A-Za-z]+", o_s):   # empty cell, or a numbers-v2 macro already checked by value
                cells.append(o); continue
            core = f"\\textbf{{{g}}}" if o_s.startswith("\\textbf{") else g
            cells.append(o[:len(o) - len(o.lstrip())] + core + o[len(o.rstrip()):])
        out.append(lead + pre + "&".join(cells) + line[len(line.rstrip()):]); i += 1
    return head + "\\midrule" + "\\\\".join(out) + "\\bottomrule" + foot


def manifest():
    """sha256 of every raw file the tables read, one line per file, plus one aggregate digest per source root."""
    import hashlib
    roots = {"grid": "data_v2/e2x_{a,a_h,b,c,c_h}", "adaptive": "data_v2/e2x_{m,s,ma}", "natural": "data_v2/v2_natural",
             "heldout": "data_v2/v2_heldout", "e1": "data_v2/e1_rope"}
    pats = {"grid": [f"data_v2/e2x_{c}/**/none.json" for c in ("a", "a_h", "b", "c", "c_h")],
            "adaptive": [f"data_v2/e2x_{c}/**/none.json" for c in ("m", "s", "ma")],
            "natural": ["data_v2/v2_natural/nat_*/**/none.json", "data_v2/v2_natural/tasks.json"],
            "heldout": ["data_v2/v2_heldout/*/*/*/*/user_task_*/*/*.json"], "e1": ["data_v2/e1_rope/*/*/*/*/user_task_*/*/*.json"]}
    lines, agg = [], {}
    for k, ps in pats.items():
        fs = sorted({f for p in ps for f in glob.glob(str(T / p), recursive=True)})
        h = hashlib.sha256()
        for f in fs:
            d = hashlib.sha256(open(f, "rb").read()).hexdigest()
            rel = os.path.relpath(f, T)
            lines.append(f"{d}  {rel}"); h.update(f"{d}  {rel}\n".encode())
        agg[k] = {"root": roots[k], "files": len(fs), "aggregate_sha256": h.hexdigest()}
    (OUT / "raw_manifest.sha256").write_text("\n".join(lines) + "\n")
    return agg


