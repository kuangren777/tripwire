def regen():
    """Rerun the deterministic derived-source scripts into a scratch copy of their output paths and compare
    byte for byte with the committed files. The committed files are never touched."""
    import hashlib, os, subprocess, tempfile
    jobs = [("e2x_rope_scope.py", ["data_v2/e2x/rope_scope_xtab.json"]),
            ("scripts/h1_blocks_by_group.py", ["data_v2/diag/h1_blocks_by_group.json"]),
            ("boundary_prevalence.py", ["data_v2/e2x/boundary_prevalence.json", "data_v2/e2x/task_level_shares.json"]),
            ("e2x_prevalence.py", ["data_v2/e2x/prevalence.json"])]
    res = {}
    tmp = Path(tempfile.mkdtemp(prefix="tw_regen_"))   # scratch, outside the repo
    for script, outs in jobs:
        src = (T / script).read_text()
        for o in outs:
            dst = tmp / o.replace("/", "__")
            if o == "data_v2/e2x/task_level_shares.json":   # boundary_prevalence reads then rewrites this file
                dst.write_bytes((T / o).read_bytes())
            src = src.replace(f'f"{{T}}/{o}"', repr(str(dst))).replace(f'"{T}/{o}"', repr(str(dst)))
            src = src.replace(o, str(dst)) if o in src else src
        f = tmp / ("run_" + Path(script).name)
        f.write_text(src)
        env = dict(os.environ, PYTHONPATH="../ext/rope/autodojo/src:../ext/rope/src:" + str(T) + ":" + str(T / "scripts"))
        r = subprocess.run([sys.executable, str(f)], cwd=str(T), env=env, capture_output=True, text=True)
        for o in outs:
            dst = tmp / o.replace("/", "__")
            same = dst.exists() and json.load(open(dst)) == json.load(open(T / o))
            res[o] = {"script": script, "rc": r.returncode, "identical_json": same,
                      "sha256_committed": hashlib.sha256((T / o).read_bytes()).hexdigest(),
                      "stderr_tail": r.stderr[-300:] if r.returncode else ""}
    return res


