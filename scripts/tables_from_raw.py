# ---------------------------------------------------------------- tex parsing and comparison
def clean_cell(s):
    s = s.strip()
    s = re.sub(r"\\textbf\{(.*)\}", r"\1", s)
    return s.replace("$-$", "-").replace("\\%", "%").strip()


def parse_rows(tex):
    """Body rows between \\midrule and \\bottomrule, split into cells; \\midrule lines inside are skipped."""
    body = tex.split("\\midrule", 1)[1].split("\\bottomrule", 1)[0]
    rows = []
    for line in body.split("\\\\"):
        line = line.replace("\\midrule", "").strip()
        if line:
            rows.append([clean_cell(c) for c in line.split("&")])
    return rows


def macros():
    m = {}
    for line in open(BRIDGE / "numbers-v2.tex"):
        r = re.match(r"\\newcommand\{\\(\w+)\}\{(.*)\}\s*$", line.strip())
        if r:
            m[r.group(1)] = r.group(2)
    return m


def expand(rows, mac):
    return [[re.sub(r"\\(\w+)", lambda x: mac.get(x.group(1), x.group(0)), c) for c in r] for r in rows]


def inline_table(label):
    src = (BRIDGE / "sec/evaluation.tex").read_text() + (BRIDGE / "sec/appendix.tex").read_text()
    i = src.index(f"\\label{{{label}}}")
    return src[i:src.index("\\end{tabular}", i) + len("\\end{tabular}")]


def compare(name, gen_rows, tex_rows):
    gen = [[clean_cell(c) for c in r] for r in gen_rows]
    out = {"cells": 0, "agree": 0, "mismatch": []}
    if len(gen) != len(tex_rows):
        out["shape"] = f"rows gen {len(gen)} vs tex {len(tex_rows)}"
    for i, (g, t) in enumerate(zip(gen, tex_rows)):
        if len(g) != len(t):
            out.setdefault("shape_rows", []).append(i)
        for j, (a, b) in enumerate(zip(g, t)):
            if not re.search(r"\d", a + b):   # row and configuration labels are compared, not counted as numeric cells
                if a != b:
                    out["mismatch"].append({"row": i, "col": j, "tex": b, "gen": a, "kind": "label"})
                continue
            if a == "" and b == "":
                continue
            out["cells"] += 1
            if a == b:
                out["agree"] += 1
            else:
                out["mismatch"].append({"row": i, "col": j, "row_label": t[0], "tex": b, "gen": a})
    return out


