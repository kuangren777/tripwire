def bootstrap(cells, arm, base="rope", rng=None):
    """Paired task-cluster bootstrap of arm minus base, pooled; security = ASR(arm) - ASR(base) on attacked cells,
    utility = CU(arm) - CU(base) on clean cells, in pp, full precision. 10,000 resamples, percentile interval.
    The random stream matches the committed scripts: h1_bootstrap.py draws strict then delegation from one
    Random(0); h1_v21_compare.py draws v2.1 from a fresh Random(0). Pass rng to continue a shared stream."""
    keys = sorted(cells[base])
    by = collections.defaultdict(list)
    for k in keys:
        by[(k[1], k[2])].append(k)
    tasks = sorted(by)

    def gaps(ts):
        s = [0, 0, 0]; c = [0, 0, 0]
        for t in ts:
            for k in by[t]:
                cl, r = cells[base][k]; x = cells[arm][k][1]
                if cl:
                    c[0] += x; c[1] += r; c[2] += 1
                else:
                    s[0] += x; s[1] += r; s[2] += 1
        return Fraction(100 * (s[0] - s[1]), s[2]), Fraction(100 * (c[0] - c[1]), c[2])
    s0, u0 = gaps(tasks)
    rng = rng or random.Random(SEED)
    ss, us = [], []
    for _ in range(B):
        s, u = gaps([tasks[rng.randrange(len(tasks))] for _ in tasks]); ss.append(s); us.append(u)
    ss.sort(); us.sort()
    lo, hi = int(0.025 * B), int(0.975 * B) - 1
    return {"sec": s0, "sec_ci": (ss[lo], ss[hi]), "cu": u0, "cu_ci": (us[lo], us[hi])}


def asr_cu(cells, keys):
    a = [cells[k][1] for k in keys if not cells[k][0]]; c = [cells[k][1] for k in keys if cells[k][0]]
    return pct(sum(a), len(a)), pct(sum(c), len(c))


