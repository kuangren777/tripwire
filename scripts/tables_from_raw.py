def grid(cond, root="data_v2"):
    """{(model, config, task): outcome} for one grid condition; a = utility, every other condition = security.
    An unfinished or errored cell is recorded in ERRORS and counted as a failed run (outcome False)."""
    out = {}
    for f in glob.glob(f"{T}/{root}/e2x_{cond}/*/*/*/*/*/e2x_{cond}/none.json"):
        p = f.split("/"); d = json.load(open(f))
        if "utility" not in d or d.get("error"):
            ERRORS.append((f"e2x_{cond}", f)); ok = False
        else:
            ok = bool(d["utility"] if cond in ("a", "a_h", "ma") else d["security"])
        out[(p[-7], p[-6], p[-3])] = ok
    return out


def heldout(model, cfg, corrected=True):
    """{(model, suite, task, attack, file): (is_clean, outcome)}; attacked outcome is ROPE's corrected security
    when corrected=True (as v2_h1_decision.py), the raw security field otherwise (as h1_bootstrap.py)."""
    out = {}
    for f in glob.glob(f"{T}/data_v2/v2_heldout/{model}/{cfg}/*/*/user_task_*/*/*.json"):
        p = f.split("/"); d = json.load(open(f))
        if "utility" not in d or d.get("error"):
            ERRORS.append(("v2_heldout", f))
        clean = p[-2] == "none"
        if clean:
            v = bool(d.get("utility"))
        elif corrected:
            v = bool(corrected_security(d, p[-4], int(re.sub(r"\D", "", p[-1][:-5]) or -1)))
        else:
            v = bool(d.get("security"))
        out[(model, p[-4], p[-3], p[-2], p[-1])] = (clean, v)
    return out


def frac(vals):
    vals = list(vals)
    return f"{sum(vals)}/{len(vals)}"


def pct(x, n):
    return Fraction(100 * x, n)


ROUNDED = []   # every rendered value: (value, decimals, fmtnum result, Python %-format result, exact .5 boundary)


def R(v, nd):
    """Render once with fmtnum (ROUND_HALF_UP on the exact Fraction) and log the Python-format result beside it."""
    new = fmt(v, nd)
    old = f"{float(v):.{nd}f}"
    fr = Fraction(v) * 10 ** nd
    ROUNDED.append((str(v), nd, new, old, fr - (fr.numerator // fr.denominator) == Fraction(1, 2)))
    return new


def f1(v):
    return R(v, 1)


def sgn(v):
    return ("+" if v >= 0 else "$-$") + R(abs(v), 1)


def neg(v):
    return ("$-$" if v < 0 else "") + R(abs(v), 1)


def tabular(spec, header, rows, mid=None):
    body = "\n".join(rows)
    return f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n"


def bold(s, on):
    return f"\\textbf{{{s}}}" if on else s


